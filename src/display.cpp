static void i2c_write(uint8_t *data, size_t len) {
    i2c_cmd_handle_t cmd = i2c_cmd_link_create();
    i2c_master_start(cmd);
    i2c_master_write_byte(cmd, (OLED_ADDR << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write(cmd, data, len, true);
    i2c_master_stop(cmd);
    i2c_master_cmd_begin(I2C_PORT, cmd, pdMS_TO_TICKS(100));
    i2c_cmd_link_delete(cmd);
}

static void oled_cmd(uint8_t c) {
    uint8_t buf[2] = {0x00, c};
    i2c_write(buf, 2);
}

static void oled_flush() {
    for (int page = 0; page < 8; ++page) {
        oled_cmd(0xB0 | page);
        oled_cmd(0x00);
        oled_cmd(0x10);
        uint8_t buf[129];
        buf[0] = 0x40;
        memcpy(&buf[1], &fb[page * 128], 128);
        i2c_write(buf, 129);
    }
}

static void draw_char(int x, int page, char c) {
    if (c >= 'a' && c <= 'z') c -= 32;
    if (c < 32 || c > 90) c = '?';
    const uint8_t *bmp = FONT5X7[c - 32];
    for (int i = 0; i < 5; ++i) fb[page * 128 + x + i] = bmp[i];
    fb[page * 128 + x + 5] = 0x00;
}

static void draw_string(int x, int page, const char *s) {
    while (*s && x < 122) { draw_char(x, page, *s++); x += 6; }
}

void display_init() {
    i2c_config_t conf = {};
    conf.mode             = I2C_MODE_MASTER;
    conf.sda_io_num       = I2C_SDA;
    conf.scl_io_num       = I2C_SCL;
    conf.sda_pullup_en    = GPIO_PULLUP_ENABLE;
    conf.scl_pullup_en    = GPIO_PULLUP_ENABLE;
    conf.master.clk_speed = 400000;
    i2c_param_config(I2C_PORT, &conf);
    i2c_driver_install(I2C_PORT, I2C_MODE_MASTER, 0, 0, 0);

    vTaskDelay(pdMS_TO_TICKS(100));
    static const uint8_t init_cmds[] = {
        0xAE,0x20,0x00,0xB0,0xC8,0x00,0x10,0x40,0x81,0x7F,0xA1,0xA6,
        0xA8,0x3F,0xA4,0xD3,0x00,0xD5,0x80,0xD9,0xF1,0xDA,0x12,0xDB,0x40,
        0x8D,0x14,0xAF
    };
    for (uint8_t c : init_cmds) oled_cmd(c);
    memset(fb, 0, sizeof(fb));
    oled_flush();

    ESP_LOGI(TAG, "SSD1306 initialized on I2C addr 0x%02X", OLED_ADDR);
}

void display_task(void *pvParameters) {
    DisplayMode mode = DisplayMode::TEMPERATURE;
    SensorData last = {};
    bool haveData = false;

    for (;;) {
        SensorData incoming;
        if (xQueueReceive(sensorQueue, &incoming, pdMS_TO_TICKS(100)) == pdTRUE) {
            last = incoming;
            haveData = true;
        }
        DisplayMode newMode;
        if (xQueueReceive(modeQueue, &newMode, 0) == pdTRUE) {
            mode = newMode;
        }

        EventBits_t bits = xEventGroupGetBits(systemEvents);
        memset(fb, 0, sizeof(fb));

        if ((bits & EVENT_ACTIVE) == 0) {
            draw_string(0, 3, "SYSTEM INACTIVE");
            oled_flush();
            vTaskDelay(pdMS_TO_TICKS(200));
            continue;
        }

        draw_string(0, 0, "ROOM MONITOR");
        char line[24] = {0};
        switch (mode) {
            case DisplayMode::TEMPERATURE:
                snprintf(line, sizeof(line), "Temperature %.1f C", last.temperature);
                break;
            case DisplayMode::HUMIDITY:
                snprintf(line, sizeof(line), "Humidity %.1f %%", last.humidity);
                break;
            case DisplayMode::LIGHT:
                snprintf(line, sizeof(line), "Light %d %%", last.lightLevel);
                break;
            case DisplayMode::MOTION:
                snprintf(line, sizeof(line), "Motion %s", last.motionDetected ? "YES" : "NO");
                break;
        }
        if (haveData) draw_string(0, 3, line);
        oled_flush();

        vTaskDelay(pdMS_TO_TICKS(200));
    }
}